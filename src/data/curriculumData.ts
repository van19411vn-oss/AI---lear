// Helper functions
export function getLessonsBySubjectAndVolume(subject: 'math' | 'vietnamese', volume: 1 | 2): CurriculumLesson[] {
  const all = subject === 'math' ? MATH_LESSONS : VIET_LESSONS;
  return all.filter((l) => l.volume === volume);
}

export function getThemesBySubjectAndVolume(subject: 'math' | 'vietnamese', volume: 1 | 2): CurriculumTheme[] {
  const all = subject === 'math' ? MATH_THEMES : VIET_THEMES;
  return all.filter((t) => t.volume === volume);
}

export function getLessonById(lessonId: string): CurriculumLesson | undefined {
  return [...MATH_LESSONS, ...VIET_LESSONS].find((l) => l.id === lessonId);
}

